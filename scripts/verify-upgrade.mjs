function snapshot(sqlite) {
  const tables = sqlite
    .prepare(
      "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    )
    .all()
  return Object.fromEntries(
    tables
      .filter(({ name }) => !/^post_text_fts_/.test(name))
      .map(({ name }) => [
        name,
        sqlite
          .prepare(`SELECT * FROM ${quote(name)}`)
          .all()
          .sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))),
      ]),
  )
}

function integrity(sqlite) {
  assert.deepEqual(sqlite.pragma('integrity_check'), [{ integrity_check: 'ok' }])
  assert.deepEqual(sqlite.pragma('foreign_key_check'), [])
}

export async function rehearseUpgrade({ schemaFixture = false, writeSchemaFixture = false } = {}) {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'adhx-upgrade-'))
  const database = path.join(temp, 'synthetic.db')
  const backup = path.join(temp, 'backup.db')
  const restored = path.join(temp, 'restored.db')
  const media = path.join(temp, 'media')
  const backupMedia = path.join(temp, 'backup-media')
  const restoredMedia = path.join(temp, 'restored-media')
  let sqlite
  let releasedRoot
  try {
    if (schemaFixture) {
      sqlite = new Database(database)
      sqlite.exec(fs.readFileSync(fixture, 'utf8'))
      sqlite.close()
    } else {
      const old = path.join(temp, 'released')
      releasedRoot = old
      fs.mkdirSync(old)
      const archive = command(
        'git',
        ['archive', release, 'src', 'drizzle', 'tsconfig.json', 'package.json'],
        root,
      )
      command('tar', ['-xf', '-', '-C', old], root, {}, archive)
      fs.symlinkSync(path.join(root, 'node_modules'), path.join(old, 'node_modules'), 'dir')
      migrate(old, database)
      sqlite = new Database(database)
      const generated = releasedSchema(sqlite)
      if (writeSchemaFixture) fs.writeFileSync(fixture, generated)
      else
        assert.equal(
          generated,
          fs.readFileSync(fixture, 'utf8'),
          'Checked-in release schema must match actual released startup code',
        )
      sqlite.close()
    }
    sqlite = new Database(database)
    sqlite.pragma('journal_mode = WAL')
    sqlite.pragma('foreign_keys = ON')
    seed(sqlite, media)
    integrity(sqlite)
    const before = snapshot(sqlite)
    const session = await new SignJWT({ userId: 'owner', username: 'synthetic_owner' })
      .setProtectedHeader({ alg: 'HS256' })
      .setIssuedAt()
      .setExpirationTime('1h')
      .sign(secret)
    // Online backup includes committed WAL data without relying on copying a live .db file.
    await sqlite.backup(backup)
    // No writer runs during this synthetic snapshot; production requires stopping
    // ADHX or coordinating writers across both the DB and media snapshot.
    fs.cpSync(media, backupMedia, { recursive: true })
    sqlite.close()
    migrate(root, database)
    sqlite = new Database(database)
    integrity(sqlite)
    const first = snapshot(sqlite)
    for (const [table, rows] of Object.entries(before)) {
      if (['migration_state', '__drizzle_migrations'].includes(table)) continue
      const columns = Object.keys(rows[0] ?? {})
      const retained = (first[table] ?? [])
        .map((row) => Object.fromEntries(columns.map((column) => [column, row[column]])))
        .sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)))
      assert.deepEqual(
        retained,
        rows,
        `Upgrade must preserve all existing ${table} rows and values`,
      )
    }
    assert.equal(
      sqlite.prepare("SELECT COUNT(*) n FROM users WHERE approval='approved'").get().n,
      2,
      'Existing members remain approved',
    )
    assert.equal(sqlite.prepare('SELECT COUNT(*) n FROM bookmarks WHERE is_private=0').get().n, 8)
    assert.equal(
      sqlite
        .prepare(
          'SELECT COUNT(*) n FROM phone_save_queue WHERE privacy_intent_version=0 AND request_id IS NULL AND publish_pending=0',
        )
        .get().n,
      4,
    )
    sqlite.close()
    migrate(root, database)
    sqlite = new Database(database)
    integrity(sqlite)
    assert.deepEqual(
      snapshot(sqlite),
      first,
      'Second startup migration must not rewrite or duplicate data',
    )
    sqlite.close()
    const verified = await jwtVerify(session, secret)
    assert.equal(
      verified.payload.userId,
      'owner',
      'Unchanged session secret preserves stateless session',
    )
    const runtime = command(
      process.execPath,
      [path.join(root, 'node_modules/tsx/dist/cli.mjs'), 'scripts/verify-upgrade-runtime.ts'],
      root,
      {
        DATABASE_PATH: database,
        MEDIA_DIR: media,
        ADHX_UPGRADE_REHEARSAL: 'synthetic-only',
        PROCESSING_MODE: 'remote',
        SEMANTIC_SEARCH: 'on',
        SEMANTIC_SPEECH: 'off',
        SEMANTIC_SCREEN_TEXT: 'off',
        KEEP_MEDIA: 'on',
        KEEP_H264: 'on',
        SESSION_SECRET: new TextDecoder().decode(secret),
      },
    )
    assert.match(runtime, /UPGRADE_RUNTIME_OK/)
    // Restore into a separate stopped-server destination, never overwrite an open file.
    fs.copyFileSync(backup, restored)
    fs.cpSync(backupMedia, restoredMedia, { recursive: true })
    sqlite = new Database(restored)
    integrity(sqlite)
    assert.deepEqual(
      snapshot(sqlite),
      before,
      'Rollback snapshot must restore exact pre-upgrade data and schema',
    )
    sqlite.close()
    if (releasedRoot) {
      migrate(releasedRoot, restored)
      sqlite = new Database(restored)
      integrity(sqlite)
      assert.deepEqual(
        snapshot(sqlite),
        before,
        'Released startup must still accept the restored old backup',
      )
      sqlite.close()
    }
    migrate(root, restored)
    sqlite = new Database(restored)
    integrity(sqlite)
    const reupgraded = snapshot(sqlite)
    // A newly introduced one-time migration runs later after restoring the
    // backup. Compare its key/value exactly, allowing only its receipt clock
    // to differ. Existing receipt timestamps and every user/work row stay exact.
    for (const row of reupgraded.migration_state) {
      if (!(before.migration_state ?? []).some((old) => old.key === row.key)) {
        const expected = first.migration_state.find((original) => original.key === row.key)
        if (expected) row.updated_at = expected.updated_at
      }
    }
    assert.deepEqual(
      reupgraded,
      first,
      'Restored backup must support the same upgrade without lost work',
    )
    for (const row of sqlite.prepare('SELECT path,bytes FROM kept_files').all()) {
      assert.equal(fs.statSync(path.join(restoredMedia, row.path)).size, row.bytes)
      assert.equal(
        hash(fs.readFileSync(path.join(restoredMedia, row.path))),
        hash(fs.readFileSync(path.join(media, row.path))),
      )
    }
    sqlite.close()
    const report = {
      status: 'passed',
      source: schemaFixture
        ? 'verified release-schema fixture'
        : 'actual released startup migration',
      release,
      accounts: 2,
      saves: 8,
      phoneReceipts: 4,
      retainedOriginals: 3,
      checks: [
        'released schema provenance',
        'consistent WAL backup',
        'account/identity/phone-key/preferences preservation',
        'stateless session preservation',
        'all legacy rows/values retained',
        'approval/privacy defaults',
        'migration idempotence',
        'integrity and foreign keys',
        'real queue retry/lease recovery',
        'backup restore and repeat upgrade',
        'retained media references',
      ],
    }
    console.log(JSON.stringify(report))
    return report
  } finally {
    if (sqlite?.open) sqlite.close()
    fs.rmSync(temp, { recursive: true, force: true })
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  rehearseUpgrade({
    schemaFixture: process.argv.includes('--schema-fixture'),
    writeSchemaFixture: process.argv.includes('--write-schema-fixture'),
  }).catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
}
