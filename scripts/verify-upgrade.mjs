const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const release = 'f5d6b37d67df5354ad10e2c97fbf4291d9483094' // v2.1.2, immutable source
const fixture = path.join(root, 'src/__tests__/fixtures/upgrade-v2.1.2.sql')
const secret = new TextEncoder().encode('synthetic-upgrade-rehearsal-only-not-a-real-secret')
const now = new Date().toISOString()
const future = new Date(Date.now() + 86_400_000).toISOString()
const past = new Date(Date.now() - 3_600_000).toISOString()
const hash = (value) => createHash('sha256').update(value).digest('hex')
const quote = (value) => `"${value.replaceAll('"', '""')}"`

function command(executable, args, cwd, env = {}, input) {
  const result = spawnSync(executable, args, {
    cwd,
    // Explicitly exclude ambient app credentials and admin grants.
    env: {
      PATH: process.env.PATH,
      HOME: process.env.HOME,
      TMPDIR: process.env.TMPDIR,
      NODE_ENV: 'test',
      ADMIN_USERNAMES: '',
      ADMIN_USER_IDS: '',
      ...env,
    },
    encoding: input || (executable === 'git' && args[0] === 'archive') ? undefined : 'utf8',
    input,
    maxBuffer: 40 * 1024 * 1024,
    timeout: 90_000,
  })
  assert.equal(
    result.status,
    0,
    `${executable} ${args.join(' ')}\n${result.stdout}\n${result.stderr}`,
  )
  return result.stdout
}

function migrate(cwd, database) {
  command(
    process.execPath,
    [path.join(root, 'node_modules/tsx/dist/cli.mjs'), 'src/lib/db/migrate.ts'],
    cwd,
    {
      DATABASE_PATH: database,
      MIGRATIONS_PATH: path.join(cwd, 'drizzle'),
    },
  )
}

/** A stable SQL snapshot generated from actual released startup code, not current test DDL. */
function releasedSchema(sqlite) {
  const objects = sqlite
    .prepare(
      "SELECT type,name,sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END,name",
    )
    .all()
    .filter((row) => !row.name.startsWith('sqlite_') && !/^post_text_fts_/.test(row.name))
  const statements = objects.map((row) => `${row.sql};`)
  for (const table of ['__drizzle_migrations', 'migration_state']) {
    for (const original of sqlite.prepare(`SELECT * FROM ${quote(table)}`).all()) {
      const row = { ...original }
      if ('created_at' in row) row.created_at = 1
      if ('updated_at' in row) row.updated_at = '2026-10-19T00:00:00.000Z'
      const values = Object.values(row).map((value) =>
        typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`,
      )
      statements.push(
        `INSERT INTO ${quote(table)} (${Object.keys(row).map(quote).join(',')}) VALUES (${values.join(',')});`,
      )
    }
  }
  return `-- Generated by scripts/verify-upgrade.mjs --write-schema-fixture\n-- Actual v2.1.2 startup migration: ${release}. Synthetic empty database only.\n${statements.join('\n\n')}\n`
}

function insert(sqlite, table, row) {
  sqlite
    .prepare(
      `INSERT INTO ${quote(table)} (${Object.keys(row).map(quote).join(',')}) VALUES (${Object.keys(
        row,
      )
        .map(() => '?')
        .join(',')})`,
    )
    .run(...Object.values(row))
}

